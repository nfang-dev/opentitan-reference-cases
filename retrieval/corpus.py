#!/usr/bin/env python3
"""Build the passage corpus for the retrieval comparison from an OpenTitan checkout.

Which files are included:

- every Markdown file under hw/ip/ and hw/ip_templates/, which are written by hand;
- for documents that exist only as Mako templates (*.md.tpl) under hw/ip_templates/,
  the rendered copy for Earl Grey under hw/top_earlgrey/ip_autogen/, or for Darjeeling
  or English Breakfast when Earl Grey has none;

except registers.md (generated by reggen), checklist.md (sign-off checklists),
anything under a dv/ directory, and symbolic links (which repeat another file).
Blocks between "BEGIN CMDGEN" and "END CMDGEN" markers are generated from the register
description and are left out of every file.

How files are split into passages:

- a passage never crosses a heading;
- within a section, paragraphs (blocks separated by blank lines) are grouped into
  passages of at most MAX_CHARS characters; a longer block is split by lines;
- each passage records its file and first and last line (1-based, inclusive), and the
  chain of headings above it.

The text that is indexed is the module name, the file name, the heading chain and the
passage, with Markdown links reduced to their link text. Both retrieval methods index
the same text.

Uses only the Python standard library.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

MAX_CHARS = 1200
TOPS = ("top_earlgrey", "top_darjeeling", "top_englishbreakfast")
EXCLUDED_NAMES = {"registers.md", "checklist.md"}

HEADING_RE = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
LINK_RE = re.compile(r"\[([^\]]*)\]\([^)]*\)")
FENCE_RE = re.compile(r"^\s*(```|~~~)")


def _excluded(rel: str) -> bool:
    parts = rel.split("/")
    return "dv" in parts or parts[-1] in EXCLUDED_NAMES


def select_files(root: Path) -> list[str]:
    """Return the corpus files as paths relative to the checkout, sorted."""
    files = set()
    for base in ("hw/ip", "hw/ip_templates"):
        for path in (root / base).rglob("*.md"):
            rel = path.relative_to(root).as_posix()
            if not _excluded(rel) and not path.is_symlink():
                files.add(rel)
    for tpl in (root / "hw/ip_templates").rglob("*.md.tpl"):
        rel = tpl.relative_to(root / "hw/ip_templates").as_posix()[: -len(".tpl")]
        if _excluded(rel):
            continue
        for top in TOPS:
            rendered = Path("hw") / top / "ip_autogen" / rel
            if (root / rendered).is_file() and not (root / rendered).is_symlink():
                files.add(rendered.as_posix())
                break
    return sorted(files)


def module_of(rel: str) -> str:
    parts = rel.split("/")
    if parts[1] in ("ip", "ip_templates"):
        return parts[2]
    return parts[3]  # hw/top_*/ip_autogen/<module>/...


def strip_generated(lines: list[str]) -> list[str]:
    """Blank out lines inside CMDGEN blocks, keeping line numbers unchanged."""
    out, inside = [], False
    for line in lines:
        if "BEGIN CMDGEN" in line:
            inside = True
            out.append("")
        elif "END CMDGEN" in line:
            inside = False
            out.append("")
        else:
            out.append("" if inside else line)
    return out


def sections(lines: list[str]):
    """Yield (heading_chain, [(line_no, text), ...]) for each section's body lines."""
    chain: list[tuple[int, str]] = []
    body: list[tuple[int, str]] = []
    in_fence = False
    for no, line in enumerate(lines, start=1):
        if FENCE_RE.match(line):
            in_fence = not in_fence
        heading = None if in_fence else HEADING_RE.match(line)
        if heading:
            yield [h for _, h in chain], body
            level = len(heading.group(1))
            chain = [(lv, h) for lv, h in chain if lv < level] + [(level, heading.group(2))]
            body = []
        else:
            body.append((no, line))
    yield [h for _, h in chain], body


def blocks(body: list[tuple[int, str]]):
    """Split section body lines into blocks separated by blank lines."""
    block: list[tuple[int, str]] = []
    for no, line in body:
        if line.strip():
            block.append((no, line))
        elif block:
            yield block
            block = []
    if block:
        yield block


def _split_long(block: list[tuple[int, str]]):
    piece: list[tuple[int, str]] = []
    size = 0
    for no, line in block:
        if piece and size + len(line) + 1 > MAX_CHARS:
            yield piece
            piece, size = [], 0
        piece.append((no, line))
        size += len(line) + 1
    if piece:
        yield piece


def passages_of(rel: str, text: str) -> list[dict]:
    lines = strip_generated(text.splitlines())
    module = module_of(rel)
    out = []
    for chain, body in sections(lines):
        groups: list[list[tuple[int, str]]] = []
        current: list[tuple[int, str]] = []
        size = 0
        for block in blocks(body):
            block_size = sum(len(t) + 1 for _, t in block)
            if block_size > MAX_CHARS:
                if current:
                    groups.append(current)
                    current, size = [], 0
                groups.extend(_split_long(block))
                continue
            if current and size + block_size > MAX_CHARS:
                groups.append(current)
                current, size = [], 0
            current.extend(block)
            size += block_size
        if current:
            groups.append(current)
        for group in groups:
            raw = "\n".join(t for _, t in group)
            if not re.search(r"[A-Za-z0-9]", raw):
                continue
            start, end = group[0][0], group[-1][0]
            heading = " > ".join(chain)
            plain = LINK_RE.sub(r"\1", raw)
            index_text = f"{module} {Path(rel).name}: {heading}\n{plain}"
            out.append({
                "id": f"{rel}:{start}-{end}",
                "path": rel,
                "start_line": start,
                "end_line": end,
                "heading": heading,
                "text": index_text,
            })
    return out


def build(root: Path) -> list[dict]:
    corpus = []
    for rel in select_files(root):
        corpus.extend(passages_of(rel, (root / rel).read_text(encoding="utf-8")))
    return corpus


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--opentitan", required=True, type=Path, help="OpenTitan checkout")
    parser.add_argument("--out", type=Path, help="write passages as JSON Lines")
    args = parser.parse_args(argv)
    corpus = build(args.opentitan)
    files = len({p["path"] for p in corpus})
    print(f"{len(corpus)} passages from {files} files", file=sys.stderr)
    if args.out:
        with args.out.open("w", encoding="utf-8") as f:
            for p in corpus:
                f.write(json.dumps(p, ensure_ascii=False) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
