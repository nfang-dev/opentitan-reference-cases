"""Generate a simulation harness around a complete OpenTitan IP for register tests.

The harness (tb_<ip>.sv) instantiates the IP's top module unchanged and:
- brings every clock (clk*_i) and reset (rst*_ni) out as a harness port;
- replaces the IP's main register bus (tl_i/tl_o) with a simple one-request-at-a-time port,
  adding the bus integrity a real bus host adds;
- holds every other input at an inactive value: the package's documented default for the
  common interface types (bus, alert, life cycle, multi-bit boolean, entropy, JTAG), and
  all zeros otherwise. The tie-offs are listed in a comment in the harness;
- brings out alert_o, the OR of the positive rail of every alert.

The port list is read from the module header with a small parser that handles the ANSI
style OpenTitan uses; Verilator then checks the generated harness when it is built.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

DEFAULTS = {
    "tlul_pkg::tl_h2d_t": "tlul_pkg::TL_H2D_DEFAULT",
    "prim_alert_pkg::alert_rx_t": "prim_alert_pkg::ALERT_RX_DEFAULT",
    "lc_ctrl_pkg::lc_tx_t": "lc_ctrl_pkg::Off",
    "prim_mubi_pkg::mubi4_t": "prim_mubi_pkg::MuBi4False",
    "prim_mubi_pkg::mubi8_t": "prim_mubi_pkg::MuBi8False",
    "prim_mubi_pkg::mubi16_t": "prim_mubi_pkg::MuBi16False",
    "prim_mubi_pkg::mubi32_t": "prim_mubi_pkg::MuBi32False",
    "edn_pkg::edn_rsp_t": "edn_pkg::EDN_RSP_DEFAULT",
    "jtag_pkg::jtag_req_t": "jtag_pkg::JTAG_REQ_DEFAULT",
    "jtag_pkg::jtag_rsp_t": "jtag_pkg::JTAG_RSP_DEFAULT",
}
SCALAR_TYPES = {"", "logic", "wire", "bit"}

PORT_RE = re.compile(r"^\s*(input|output|inout)\s+(.*?)\s*(\w+)\s*,?\s*(?://.*)?$")
DIMS_RE = re.compile(r"(\[[^\]]+\])")


@dataclass
class Port:
    direction: str
    type: str      # e.g. "tlul_pkg::tl_h2d_t", "logic", ""
    dims: str      # packed dimensions as written, e.g. "[NumAlerts-1:0]"
    name: str


def module_header(text: str, module: str) -> tuple[list[str], str]:
    """Packages imported in the module header, and the text of its port list."""
    m = re.search(rf"^module\s+{re.escape(module)}\b(.*?)\);\s*$", text, re.S | re.M)
    if not m:
        raise ValueError(f"module {module} not found")
    header = m.group(1)
    imports = re.findall(r"import\s+(\w+)::\*", header)
    # The port list is the last parenthesised list of the header.
    depth, start = 0, None
    for i, ch in enumerate(header):
        if ch == "(":
            if depth == 0:
                start = i
            depth += 1
        elif ch == ")":
            depth -= 1
    return imports, header[start + 1:] if start is not None else ""


def parse_ports(text: str, module: str) -> tuple[list[str], list[Port]]:
    imports, port_text = module_header(text, module)
    ports = []
    for line in port_text.splitlines():
        line = re.sub(r"//.*", "", line)
        if not line.strip() or line.strip().startswith("`"):
            continue
        m = PORT_RE.match(line)
        if not m:
            continue
        kind = m.group(2)
        dims = " ".join(DIMS_RE.findall(kind))
        typ = DIMS_RE.sub("", kind).strip()
        ports.append(Port(m.group(1), typ, dims, m.group(3)))
    return imports, ports


def qualify(expr: str, packages: dict[str, str]) -> str:
    """Prefix identifiers defined in an imported package with that package's name."""
    def repl(m):
        ident = m.group(0)
        for pkg, body in packages.items():
            if re.search(rf"\b(parameter|localparam|typedef)\b[^;]*\b{ident}\b\s*(=|;)", body):
                return f"{pkg}::{ident}"
        return ident
    return re.sub(r"(?<![:\w'])([A-Za-z_]\w*)(?!\s*::)", repl, expr)


def tie_value(port: Port, packages: dict[str, str]) -> str:
    default = DEFAULTS.get(port.type)
    if default is None:
        return "'0"
    if not port.dims:
        return default
    m = re.fullmatch(r"\[\s*(.+?)\s*-\s*1\s*:\s*0\s*\]", port.dims)
    if not m:
        return "'0"
    return f"{{{qualify(m.group(1), packages)}{{{default}}}}}"


def harness(module: str, text: str, package_texts: dict[str, str]) -> tuple[str, list[str]]:
    imports, ports = parse_ports(text, module)
    packages = {p: package_texts.get(p, "") for p in imports}
    clocks = [p.name for p in ports if p.direction == "input" and re.fullmatch(r"clk\w*_i", p.name)]
    resets = [p.name for p in ports if p.direction == "input" and re.fullmatch(r"rst\w*_ni", p.name)]
    alerts = [p for p in ports if p.direction == "output" and p.type == "prim_alert_pkg::alert_tx_t"]

    lines = ["// Generated by csr/gen_harness.py. Do not edit.", "//",
             f"// Harness for register tests of {module}. Inputs held at inactive values:"]
    decls, conns, notes = [], [], []
    for p in ports:
        if p.name in clocks or p.name in resets:
            conns.append(f"    .{p.name}")
        elif p.name == "tl_i":
            conns.append("    .tl_i (tl_h2d)")
        elif p.name == "tl_o":
            conns.append("    .tl_o (tl_d2h)")
        elif p in alerts:
            dims = qualify(p.dims, packages)
            decls.append(f"  prim_alert_pkg::alert_tx_t {dims} {p.name}_w;")
            conns.append(f"    .{p.name} ({p.name}_w)")
        elif p.direction == "input":
            value = tie_value(p, packages)
            notes.append(f"//   {p.name}: {value}")
            conns.append(f"    .{p.name} ({value})")
        else:
            conns.append(f"    .{p.name} ()")
    lines += notes
    port_lines = [f"  input  logic {c}," for c in clocks + resets]
    port_lines += [
        "  input  logic        reg_req_i,",
        "  input  logic        reg_we_i,",
        "  input  logic [31:0] reg_addr_i,",
        "  input  logic [31:0] reg_wdata_i,",
        "  output logic        reg_gnt_o,",
        "  output logic        reg_rvalid_o,",
        "  output logic [31:0] reg_rdata_o,",
        "  output logic        reg_error_o,",
        "  output logic        alert_o",
    ]
    body = [
        f"module tb_{module} (",
        *port_lines,
        ");",
        "",
        "  tlul_pkg::tl_h2d_t tl_h2d_raw, tl_h2d;",
        "  tlul_pkg::tl_d2h_t tl_d2h;",
        "",
        "  always_comb begin",
        "    tl_h2d_raw           = tlul_pkg::TL_H2D_DEFAULT;",
        "    tl_h2d_raw.a_valid   = reg_req_i;",
        "    tl_h2d_raw.a_opcode  = reg_we_i ? tlul_pkg::PutFullData : tlul_pkg::Get;",
        "    tl_h2d_raw.a_size    = 2'd2;",
        "    tl_h2d_raw.a_mask    = 4'hf;",
        "    tl_h2d_raw.a_address = reg_addr_i;",
        "    tl_h2d_raw.a_data    = reg_we_i ? reg_wdata_i : 32'h0;",
        "    tl_h2d_raw.d_ready   = 1'b1;",
        "  end",
        "",
        "  tlul_cmd_intg_gen u_cmd_intg_gen (.tl_i(tl_h2d_raw), .tl_o(tl_h2d));",
        "",
        "  assign reg_gnt_o    = tl_d2h.a_ready;",
        "  assign reg_rvalid_o = tl_d2h.d_valid;",
        "  assign reg_rdata_o  = tl_d2h.d_data;",
        "  assign reg_error_o  = tl_d2h.d_error;",
        "",
        *decls,
    ]
    alert_terms = []
    for p in alerts:
        body += [f"  logic alert_any_{p.name};",
                 "  always_comb begin",
                 f"    alert_any_{p.name} = 1'b0;",
                 f"    for (int i = 0; i < $size({p.name}_w); i++) alert_any_{p.name} |= {p.name}_w[i].alert_p;",
                 "  end"]
        alert_terms.append(f"alert_any_{p.name}")
    alert_expr = " | ".join(alert_terms) or "1'b0"
    body.append(f"  assign alert_o = {alert_expr};")
    body += ["", f"  {module} u_dut (", ",\n".join(conns), "  );", "", "endmodule", ""]
    return "\n".join(lines + [""] + body), clocks + resets


def core_file(module: str, ip_core: str) -> str:
    return f"""CAPI=2:
# Generated by csr/gen_harness.py. Do not edit.
name: "nfang:csr:tb_{module}:0.1"
filesets:
  files_tb:
    depend:
      - {ip_core}
      - lowrisc:ip:tlul
    files:
      - tb_{module}.sv
    file_type: systemVerilogSource
targets:
  default:
    filesets:
      - files_tb
    toplevel: tb_{module}
    tools:
      verilator:
        mode: lint-only
"""


def core_name(core_text: str) -> str:
    return re.search(r'^name:\s*"?([^"\s]+)"?', core_text, re.M).group(1)


def write(out_dir: Path, module: str, ip_text: str, package_texts: dict[str, str],
          ip_core: str) -> list[str]:
    out_dir.mkdir(parents=True, exist_ok=True)
    sv, clocks_resets = harness(module, ip_text, package_texts)
    (out_dir / f"tb_{module}.sv").write_text(sv, encoding="utf-8")
    (out_dir / f"tb_{module}.core").write_text(core_file(module, ip_core), encoding="utf-8")
    return clocks_resets
